export const ALL_PUBLICATIONS: PublicationItem[] = [
  ...CHAPTERS_IN_BOOKS,
  ...JOURNAL_ARTICLES,
  ...CONFERENCE_PAPERS,
  ...BOOK_REVIEWS,
];

export function searchPublications(query: string, type?: string, topic?: string) {
  let list = ALL_PUBLICATIONS;

  if (type && type !== "all") {
    list = list.filter((item) => item.type === type);
  }

  if (topic && topic !== "all") {
    list = list.filter((item) => item.topic === topic);
  }

  const q = query.trim().toLowerCase();
  if (!q) return list;

  return list.filter((item) =>
    [item.title, item.source, item.citation, item.year, item.coauthor ?? "", item.topic ?? ""].some((f) =>
      f.toLowerCase().includes(q)
    )
  );
}
